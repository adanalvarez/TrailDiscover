def _dd_create_tactic_group_widgets(tactic, events):
    widgets = []
    x, y = 0, 0
    for event in events:
        if x + 4 > 12:
            x, y = 0, y + 2
        widgets.extend(_dd_tactic_widgets(event, tactic, x, y))
        x += 4
    return widgets, y + 2



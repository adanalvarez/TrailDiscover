# --- ATT&CK index and Navigator layer (Insights page) -------------------

# Enterprise tactics in ATT&CK matrix order.
ATTACK_TACTIC_ORDER = [
    "TA0043", "TA0042", "TA0001", "TA0002", "TA0003", "TA0004", "TA0005",
    "TA0006", "TA0007", "TA0008", "TA0009", "TA0011", "TA0010", "TA0040",
]
# Accepts "T1098 - Name" and the variants found in the data ("T1078.004: Name", "T1562.001 Name").
ATTACK_ID_RE = re.compile(r"^\s*(TA?\d{4}(?:\.\d{3})?)\b")


def _attack_ids(values):
    ids = []
    for value in values:
        match = ATTACK_ID_RE.match(value)
        if match and match.group(1) not in ids:
            ids.append(match.group(1))
    return ids


def _attack_placements(events, lookup):
    """Place each event under (tactic, technique) pairs that ATT&CK itself lists.

    An event tagged with tactics A and B and technique T is counted under (A, T) only when
    ATT&CK lists T under A. Tagged tactics with no valid technique are reported as unplaced.
    """
    cells, unplaced, unknown = {}, {}, {}
    for event in events:
        event_id = f"{event['awsService']}-{event['eventName']}"
        tactics = _attack_ids(event.get("mitreAttackTactics", []))
        techniques = _attack_ids(event.get("mitreAttackTechniques", []) + event.get("mitreAttackSubTechniques", []))
        placed = set()
        for technique in techniques:
            info = lookup["techniques"].get(technique)
            if not info:
                unknown.setdefault(technique, []).append(event_id)
                continue
            for tactic in tactics:
                if tactic in info["tactics"]:
                    cells.setdefault((tactic, technique), []).append(event_id)
                    placed.add(tactic)
        for tactic in tactics:
            if tactic not in placed:
                unplaced.setdefault(tactic, []).append(event_id)
    return cells, unplaced, unknown


def _generate_attack_files(events: List[dict]):
    with open(ATTACK_LOOKUP, "r", encoding="utf-8") as fh:
        lookup = json.load(fh)
    with open(EVENTS_JSON, "rb") as fh:
        data_version = hashlib.sha256(fh.read()).hexdigest()[:12]

    cells, unplaced, unknown = _attack_placements(events, lookup)
    order = {tactic: i for i, tactic in enumerate(ATTACK_TACTIC_ORDER)}
    cell_keys = sorted(cells, key=lambda k: (order.get(k[0], 99), k[1]))

    used = {technique for _, technique in cells}
    used |= {technique.split(".")[0] for technique in used}
    index = {
        "attackVersion": ATTACK_VERSION,
        "dataVersion": data_version,
        "tactics": [{"id": t, **lookup["tactics"][t]} for t in ATTACK_TACTIC_ORDER if t in lookup["tactics"]],
        "techniques": {
            t: {"name": lookup["techniques"][t]["name"], "parent": t.split(".")[0] if "." in t else None}
            for t in sorted(used) if t in lookup["techniques"]
        },
        "cells": [{"tactic": k[0], "technique": k[1], "events": sorted(cells[k])} for k in cell_keys],
        "unplaced": [{"tactic": t, "events": sorted(unplaced[t])} for t in sorted(unplaced, key=lambda t: order.get(t, 99))],
        "unknownTechniques": [{"technique": t, "events": sorted(ids)} for t, ids in sorted(unknown.items())],
    }
    with open(ATTACK_INDEX_JSON, "w", encoding="utf-8") as fh:
        json.dump(index, fh, indent=1)
        fh.write("\n")

    # Presence-only ATT&CK Navigator layer: no scores, because counts reflect how the catalogue
    # was curated, not how often attackers use a technique.
    wild = {f"{e['awsService']}-{e['eventName']}" for e in events if e.get("usedInWild")}
    has_subtechniques = {(k[0], k[1].split(".")[0]) for k in cell_keys if "." in k[1]}
    techniques = []
    for tactic, technique in cell_keys:
        ids = sorted(cells[(tactic, technique)])
        in_wild = sum(1 for i in ids if i in wild)
        techniques.append({
            "techniqueID": technique,
            "tactic": lookup["tactics"][tactic]["shortname"],
            "color": "#8ECAE6",
            "comment": f"{len(ids)} catalogued CloudTrail event{'s' if len(ids) != 1 else ''} in TrailDiscover ({in_wild} seen in the wild)",
            "enabled": True,
            "metadata": [{"name": "Events", "value": ", ".join(ids)}],
            "links": [{"label": "Open in TrailDiscover", "url": f"{SITE_URL}?technique={technique}&tactic={tactic}"}],
            "showSubtechniques": (tactic, technique) in has_subtechniques,
        })
    layer = {
        "name": "TrailDiscover: catalogued CloudTrail events",
        "versions": {"attack": ATTACK_VERSION.split(".")[0], "navigator": "5.1.0", "layer": "4.5"},
        "domain": "enterprise-attack",
        "description": (
            "ATT&CK techniques that TrailDiscover maps catalogued AWS CloudTrail API calls to. "
            "Presence only: it does not show how often attackers use a technique, risk, or detection coverage. "
            f"Generated from events.json (data version {data_version}), ATT&CK v{ATTACK_VERSION}."
        ),
        "sorting": 0,
        "layout": {"layout": "side", "showID": True, "showName": True, "showAggregateScores": False, "countUnscored": False},
        "hideDisabled": False,
        "techniques": techniques,
        "gradient": {"colors": ["#ffffff", "#8ECAE6"], "minValue": 0, "maxValue": 1},
        "legendItems": [{"label": "Catalogued in TrailDiscover", "color": "#8ECAE6"}],
        "metadata": [{"name": "Source", "value": f"{SITE_URL}insights.html#techniques"}],
        "links": [{"label": "TrailDiscover Insights", "url": f"{SITE_URL}insights.html#techniques"}],
        "showTacticRowBackground": True,
        "tacticRowBackground": "#023047",
        "selectTechniquesAcrossTactics": False,
        "selectSubtechniquesWithParent": False,
    }
    with open(ATTACK_LAYER_JSON, "w", encoding="utf-8") as fh:
        json.dump(layer, fh, indent=1)
        fh.write("\n")
    print(f"  ✓ Generated {os.path.relpath(ATTACK_INDEX_JSON, ROOT_DIR)} and "
          f"{os.path.relpath(ATTACK_LAYER_JSON, ROOT_DIR)} ({len(cell_keys)} tactic/technique cells, ATT&CK v{ATTACK_VERSION})")
    for technique, ids in sorted(unknown.items()):
        print(f"  ! {technique} is not an active technique in ATT&CK v{ATTACK_VERSION}: {', '.join(ids)}")


def step_generate(filter_tactics=None, wild_only=False):
    """Generate events.json, events.csv, datadog_dashboard.json and the ATT&CK files."""
    print("\n[ Step 4/4 ] Generating output files …")
    events = _load_all_events()
    _generate_events_json(events)
    _generate_events_csv(events)
    _generate_datadog_dashboard(events, filter_tactics=filter_tactics, wild_only=wild_only)
    _generate_attack_files(events)


